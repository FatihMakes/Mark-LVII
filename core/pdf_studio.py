def generate_pdf(
    content: str,
    output_filename: str = "document.pdf",
    title: str = "Document",
    query: str = "",
    open_preview: bool = True
) -> Dict[str, Any]:
    """
    Compiles content into a verified PDF file.
    """
    dest = Path(output_filename).expanduser()
    if not dest.is_absolute():
        dest = DESKTOP / output_filename
    if dest.suffix.lower() != ".pdf":
        dest = dest.with_suffix(".pdf")
    dest.parent.mkdir(parents=True, exist_ok=True)

    final_content = synthesize_content_if_needed(content, query=query)

    # 1. Primary Engine: ReportLab Platypus
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable, Table, TableStyle
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib import colors

        canvas_maker = _create_numbered_canvas_class(title)

        doc = SimpleDocTemplate(
            str(dest),
            pagesize=letter,
            leftMargin=54, rightMargin=54,
            topMargin=54, bottomMargin=54
        )
        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            'DocTitle',
            parent=styles['Title'],
            fontName='Helvetica-Bold',
            fontSize=20,
            leading=24,
            textColor=colors.HexColor('#0f172a'),
            spaceAfter=6,
            alignment=0
        )
        h1_style = ParagraphStyle(
            'DocH1',
            parent=styles['Heading1'],
            fontName='Helvetica-Bold',
            fontSize=13,
            leading=17,
            textColor=colors.HexColor('#1d4ed8'),
            spaceBefore=14,
            spaceAfter=6,
            keepWithNext=True
        )
        h2_style = ParagraphStyle(
            'DocH2',
            parent=styles['Heading2'],
            fontName='Helvetica-Bold',
            fontSize=11,
            leading=15,
            textColor=colors.HexColor('#334155'),
            spaceBefore=10,
            spaceAfter=4,
            keepWithNext=True
        )
        body_style = ParagraphStyle(
            'DocBody',
            parent=styles['Normal'],
            fontName='Helvetica',
            fontSize=9.5,
            leading=14,
            textColor=colors.HexColor('#1e293b'),
            spaceAfter=5
        )
        bullet_style = ParagraphStyle(
            'DocBullet',
            parent=body_style,
            leftIndent=14,
            firstLineIndent=-10,
            spaceAfter=3
        )
        code_style = ParagraphStyle(
            'DocCode',
            parent=body_style,
            fontName='Courier',
            fontSize=8,
            leading=11,
            textColor=colors.HexColor('#0f172a'),
            backColor=colors.HexColor('#f8fafc'),
            spaceBefore=4,
            spaceAfter=4
        )

        story = []
        if title:
            story.append(Paragraph(clean_markup(title), title_style))
            story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#2563eb'), spaceBefore=2, spaceAfter=12))

        in_code_block = False
        code_lines: List[str] = []

        for raw_line in final_content.splitlines():
            line = raw_line.rstrip()
            if line.startswith("```"):
                if in_code_block:
                    block_txt = "<br/>".join(clean_markup(cl) for cl in code_lines)
                    story.append(Paragraph(block_txt, code_style))
                    story.append(Spacer(1, 4))
                    code_lines = []
                    in_code_block = False
                else:
                    in_code_block = True
                    code_lines = []
                continue

            if in_code_block:
                code_lines.append(line)
                continue

            sline = line.strip()
            if not sline:
                story.append(Spacer(1, 5))
                continue

            if sline.startswith("# "):
                story.append(Paragraph(clean_markup(sline[2:]), h1_style))
            elif sline.startswith("## "):
                story.append(Paragraph(clean_markup(sline[3:]), h2_style))
            elif sline.startswith("### "):
                story.append(Paragraph(clean_markup(sline[4:]), h2_style))
            elif sline.startswith("- ") or sline.startswith("* "):
                story.append(Paragraph(f"&bull; {clean_markup(sline[2:])}", bullet_style))
            elif re.match(r'^\d+\.\s', sline):
                m = re.match(r'^(\d+\.)\s*(.*)', sline)
                if m:
                    story.append(Paragraph(f"<b>{m.group(1)}</b> {clean_markup(m.group(2))}", bullet_style))
                else:
                    story.append(Paragraph(clean_markup(sline), body_style))
            elif sline.startswith("---") or sline.startswith("___"):
                story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#cbd5e1'), spaceBefore=6, spaceAfter=6))
            else:
                story.append(Paragraph(clean_markup(sline), body_style))

        if in_code_block and code_lines:
            block_txt = "<br/>".join(clean_markup(cl) for cl in code_lines)
            story.append(Paragraph(block_txt, code_style))

        doc.build(story, canvasmaker=canvas_maker)

    except Exception as rl_err:
        logger.warning(f"ReportLab compilation failed: {rl_err}. Falling back to PyMuPDF renderer.")
        # Binary Fallback: PyMuPDF page generator
        try:
            import pymupdf
            doc = pymupdf.open()
            page = doc.new_page(width=612, height=792)  # Letter
            p_y = 60
            page.insert_text((54, p_y), title, fontsize=18, fontname="helv-bold")
            p_y += 30
            for line in final_content.splitlines():
                if p_y > 730:
                    page = doc.new_page(width=612, height=792)
                    p_y = 60
                page.insert_text((54, p_y), line[:90], fontsize=10, fontname="helv")
                p_y += 15
            doc.save(str(dest))
            doc.close()
        except Exception as mu_err:
            return {
                "status": "error",
                "message": f"Both PDF rendering engines failed: {rl_err} | {mu_err}"
            }

    # Validate output
    val = validate_pdf(str(dest))
    if not val.get("is_valid"):
        return {
            "status": "validation_failed",
            "message": f"Generated PDF failed verification: {val.get('error')}",
            "details": val
        }

    # Launch in macOS Preview if requested
    if open_preview and sys.platform == "darwin":
        try:
            subprocess.Popen(["open", "-a", "Preview", str(dest)])
        except Exception as e:
            logger.debug(f"Could not open Preview: {e}")

    return {
        "status": "success",
        "path": str(dest),
        "filename": dest.name,
        "pages": val.get("pages", 1),
        "file_size": val.get("file_size", 0),
        "message": f"Generated and verified PDF at {dest.name} ({val.get('pages', 1)} pages, {val.get('file_size', 0)} bytes). Opened in Preview."
    }


def validate_pdf(file_path: str) -> Dict[str, Any]:
    """
    Checks that the PDF exists, size > 500 bytes, has valid PyMuPDF structure and > 0 pages.
    """
    p = Path(file_path).expanduser()
    if not p.exists():
        return {"is_valid": False, "error": f"File does not exist: {file_path}"}

    sz = p.stat().st_size
    if sz < 500:
        return {"is_valid": False, "error": f"File size too small ({sz} bytes). PDF likely corrupted or empty."}

    try:
        import pymupdf
        doc = pymupdf.open(str(p))
        page_count = len(doc)
        if page_count < 1:
            doc.close()
            return {"is_valid": False, "error": "PDF has zero pages."}

        first_page_text = doc[0].get_text()
        doc.close()

        return {
            "is_valid": True,
            "pages": page_count,
            "file_size": sz,
            "has_text": len(first_page_text.strip()) > 0,
            "first_page_preview": first_page_text[:150]
        }
    except Exception as e:
        return {"is_valid": False, "error": f"PyMuPDF structure check failed: {str(e)}"}
