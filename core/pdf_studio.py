"""
JARVIS H3.2 — Professional PDF Studio & Document Synthesizer
Generates publication-quality multi-page PDF documents with:
  - Running headers & footers with dynamic "Page X of Y" numbering (two-pass canvas).
  - Clean typographic hierarchy (ReportLab Platypus).
  - Code syntax formatting, styled tables, and alert callouts.
  - Strict PyMuPDF binary verification (structure, size > 500B, page count > 0).
  - Native macOS Preview integration (open -a Preview).
  - Auto-synthesis when queries or problem statements lack pre-rendered markdown.
"""

import os
